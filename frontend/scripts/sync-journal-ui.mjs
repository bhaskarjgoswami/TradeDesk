// Copy the local desktop journal's UI (repo root) into the web build, unchanged
// except for two injected <script> tags that connect it to TradeDesk cloud.
// Source of truth stays at the repo root (also served by `python3 app.py`).
//   node scripts/sync-journal-ui.mjs          -> write frontend/app/index.html + public/*
//   node scripts/sync-journal-ui.mjs --check  -> exit 1 if the copies are stale (CI)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const front = join(here, "..");
const ASSETS = ["language.js", "onboarding.js", "feedback-page.js", "trade-drafts.js", "broker-import.js", "workspace.js", "calendar.js", "trade.js", "playbook.js", "profile.js", "meditation.js",
                "workspace.css", "theme.css", "theme-mercury.css"];
const BANNER = "GENERATED by scripts/sync-journal-ui.mjs from the repo-root journal UI. Edit the original, then re-run the sync.";

const outputs = {};
for (const f of ASSETS) {
  const src = readFileSync(join(root, f), "utf8");
  const banner = f.endsWith(".css") ? `/* ${BANNER} */\n` : `// ${BANNER}\n`;
  outputs[join(front, "public", f)] = banner + src;
}
for (const lang of ["en","hi","es","fr","de","pt","ar","zh-CN"]) {
  outputs[join(front,"public","locales",lang+".json")] = readFileSync(join(root,"locales",lang+".json"),"utf8");
}
let html = readFileSync(join(root, "index.html"), "utf8");
const inject = `<head>\n<!-- ${BANNER} -->\n<script src="/cloud-boot.js"></script>\n<script type="module" src="/src/cloud/shim.js"></script>\n<link rel="manifest" href="/manifest.webmanifest">\n<link rel="icon" type="image/svg+xml" href="/favicon.svg">`;
if (!/<head>/i.test(html)) throw new Error("journal index.html has no <head>");
html = html.replace(/<head>/i, inject);
outputs[join(front, "app", "index.html")] = html;

const check = process.argv.includes("--check");
let stale = [];
for (const [path, content] of Object.entries(outputs)) {
  const cur = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (cur === content) continue;
  if (check) stale.push(path.replace(front + "/", ""));
  else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, content); }
}
if (check && stale.length) { console.error("Journal UI copies are stale; run `npm run sync:journal`:\n  " + stale.join("\n  ")); process.exit(1); }
console.log(check ? "journal UI copies up to date" : `synced ${Object.keys(outputs).length} journal UI files`);
